const TABLE: Array<{ name: string; lab: Lab }> = NAMES.map(([name, hex]) => ({
  name,
  lab: rgbToOklab(hexToRgb(hex)),
}))

export function nameColor(rgb: RGB, lab: Lab = rgbToOklab(rgb)): string {
  let best = TABLE[0]
  let bestD = Infinity
  for (const e of TABLE) {
    const d = labDistance(lab, e.lab)
    if (d < bestD) {
      bestD = d
      best = e
    }
  }
  return best.name
}
